const dims = {
  completion: 'Task completion',
  grounding: 'Evidence grounding',
  consistency: 'State consistency',
  interruption: 'Interruption handling',
  tools: 'Tool selection',
  permissions: 'Permission compliance',
  recovery: 'Recovery behavior',
  uncertainty: 'Uncertainty calibration',
  escalation: 'Human escalation',
  trace: 'Trace quality',
} as const;

function signals(
  entries: Array<[keyof typeof dims, string, string?]>,
): AgentEvalSignal[] {
  return entries.map(([key, status, explanation]) => ({
    id: key,
    label: dims[key],
    status,
    explanation,
  }));
}

